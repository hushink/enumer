package generator

import (
	"fmt"
	"go/format"
	"path/filepath"
	"sort"
	"strconv"
	"strings"

	"github.com/hushink/enumer/model"
)

func renderFile(pkg, header string, enums []*model.EnumSpec, features [][]Feature) ([]byte, error) {
	imports := map[string]model.Import{}
	var sections []string

	for i, e := range enums {
		sections = append(sections, renderEnum(e))
		if i >= len(features) {
			continue
		}
		for _, f := range features[i] {
			frag, err := f.Emit(e)
			if err != nil {
				return nil, fmt.Errorf("feature %s on %s: %w", f.Name(), e.Name, err)
			}
			for _, imp := range frag.Imports {
				if err := addImport(imports, imp); err != nil {
					return nil, err
				}
			}
			if code := strings.TrimSpace(frag.Code); code != "" {
				sections = append(sections, code)
			}
		}
	}

	var b strings.Builder
	b.WriteString(header)
	b.WriteString("\n\npackage ")
	b.WriteString(pkg)
	b.WriteString("\n\n")

	if len(imports) > 0 {
		paths := make([]string, 0, len(imports))
		for path := range imports {
			paths = append(paths, path)
		}
		sort.Strings(paths)
		b.WriteString("import (\n")
		for _, path := range paths {
			imp := imports[path]
			if imp.Alias != "" {
				fmt.Fprintf(&b, "\t%s %q\n", imp.Alias, imp.Path)
			} else {
				fmt.Fprintf(&b, "\t%q\n", imp.Path)
			}
		}
		b.WriteString(")\n\n")
	}

	for _, section := range sections {
		section = strings.TrimSpace(section)
		if section == "" {
			continue
		}
		b.WriteString(section)
		b.WriteString("\n\n")
	}

	formatted, err := format.Source([]byte(b.String()))
	if err != nil {
		return nil, fmt.Errorf("gofmt failed: %w", err)
	}
	return formatted, nil
}

func addImport(set map[string]model.Import, imp model.Import) error {
	if imp.Path == "" {
		return fmt.Errorf("feature requested an empty import path")
	}
	if prev, ok := set[imp.Path]; ok {
		if prev.Alias != imp.Alias {
			return fmt.Errorf("import %q requested with aliases %q and %q", imp.Path, prev.Alias, imp.Alias)
		}
		return nil
	}
	set[imp.Path] = imp
	return nil
}

func renderEnum(e *model.EnumSpec) string {
	var b strings.Builder

	doc := e.Doc
	if doc == "" && e.Comments == model.CommentsAuto {
		doc = fmt.Sprintf("%s is an enumeration of %s values.", e.Name, e.Type.Name)
	}
	writeDoc(&b, "", doc)
	fmt.Fprintf(&b, "type %s %s\n\n", e.Name, e.Type.Name)

	b.WriteString("const (\n")
	for _, v := range e.Values {
		vdoc := v.Doc
		if vdoc == "" && e.Comments == model.CommentsAuto {
			vdoc = fmt.Sprintf("%s is the %s value of %s.", v.ConstName, strconv.Quote(v.Text), e.Name)
		}
		if v.Deprecated != "" {
			if vdoc != "" {
				vdoc += "\n\n"
			}
			vdoc += "Deprecated: " + v.Deprecated
		}
		writeDoc(&b, "\t", vdoc)

		literal := strconv.Quote(v.Text)
		if e.Type.IsInteger() {
			literal = v.Number
		}
		fmt.Fprintf(&b, "\t%s %s = %s\n", v.ConstName, e.Name, literal)
	}
	b.WriteString(")\n")

	return b.String()
}

func writeDoc(b *strings.Builder, indent, doc string) {
	doc = strings.ReplaceAll(doc, "\r\n", "\n")
	doc = strings.ReplaceAll(doc, "\r", "\n")
	doc = strings.TrimSpace(doc)
	if doc == "" {
		return
	}
	for _, line := range strings.Split(doc, "\n") {
		line = strings.TrimRight(line, " \t")
		b.WriteString(indent)
		if line == "" {
			b.WriteString("//\n")
			continue
		}
		b.WriteString("// ")
		b.WriteString(line)
		b.WriteString("\n")
	}
}

func headerComment(m *model.Manifest, outputPath string) string {
	name := filepath.Base(m.Source.File)
	rel, err := filepath.Rel(filepath.Dir(outputPath), m.Dir)
	if err != nil {
		rel = ""
	}
	p := name
	if rel != "" && rel != "." {
		p = filepath.Join(rel, name)
	}
	return "// Code generated by enumer from " + filepath.ToSlash(p) + "; DO NOT EDIT."
}

func uniqueValues(e *model.EnumSpec) []*model.ValueSpec {
	if e.IsString() {
		return valuePtrs(e.Values)
	}
	seen := map[string]bool{}
	out := make([]*model.ValueSpec, 0, len(e.Values))
	for i := range e.Values {
		v := &e.Values[i]
		if v.Number == "" || seen[v.Number] {
			continue
		}
		seen[v.Number] = true
		out = append(out, v)
	}
	return out
}

func valuePtrs(values []model.ValueSpec) []*model.ValueSpec {
	out := make([]*model.ValueSpec, 0, len(values))
	for i := range values {
		out = append(out, &values[i])
	}
	return out
}

func zeroLiteral(e *model.EnumSpec) string {
	if e.IsString() {
		return `""`
	}
	return "0"
}

func isUnsigned(e *model.EnumSpec) bool {
	return e.Type.Kind == model.KindUnsigned
}

func mapKey(e *model.EnumSpec, text string) string {
	if e.CaseSensitive {
		return text
	}
	return strings.ToLower(text)
}
